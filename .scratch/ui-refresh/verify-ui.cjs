const root = path.resolve(__dirname, '../..');
const seed = JSON.parse(fs.readFileSync(path.join(root, 'data/initial_data.json'), 'utf8'));
const server = http.createServer((req, res) => {
  const file = path.resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://localhost').pathname));
  if (!file.startsWith(root + path.sep)) { res.writeHead(403).end(); return; }
  const mime = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png' };
  res.setHeader('Content-Type', mime[path.extname(file)] || 'application/octet-stream');
  res.setHeader('Content-Security-Policy', "script-src 'self'; object-src 'self'");
  fs.readFile(file, (err, content) => { if (err) res.writeHead(404).end(); else res.end(content); });
});
